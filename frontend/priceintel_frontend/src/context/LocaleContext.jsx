export const localeOptions = [
  { value: "en", label: "English", nativeLabel: "English" },
  { value: "ar", label: "Arabic", nativeLabel: "العربية" },
  { value: "ur", label: "Urdu", nativeLabel: "اردو" },
];

export function LocaleProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const savedLanguage = localStorage.getItem("priceintel_language");
    return localeOptions.some((option) => option.value === savedLanguage) ? savedLanguage : "en";
  });

  useEffect(() => {
    const direction = language === "en" ? "ltr" : "rtl";
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    localStorage.setItem("priceintel_language", language);
  }, [language]);

  const t = (text) => translations[language]?.[text] || text;

  return (
    <LocaleContext.Provider value={{ language, setLanguage, localeOptions, t }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) {
    return { language: "en", setLanguage: () => {}, localeOptions, t: (text) => text };
  }
  return context;
}